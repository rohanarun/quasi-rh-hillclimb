"""Generate exact Lean Bernstein instances from rational scalar receipts.

Uses Sil's generic Bernstein and cleared-gate lemmas (Apache-2.0), as in
Jacob Sussman's PR86. New arithmetic instances generated with OpenAI Codex.
"""
import json,sys
from pathlib import Path
import sympy as sp
from scalar import bernstein,v,Q
import hashlib

def rat(x):
    x=Q(x)
    a=f'{x.p}' if x.q==1 else f'{x.p} / {x.q}'
    return f'({a} : ℝ)'

def poly(expr):
    p=sp.Poly(expr,v)
    return ' + '.join(rat(p.nth(i))+(f' * v ^ {i}' if i>1 else ' * v' if i else '') for i in range(p.degree()+1) if p.nth(i)) or '(0 : ℝ)'

SPEC=[
 ('q_lower','QLower','B0 L0 L A D','q_lower'),
 ('q_upper','QUpper','B0 L0 L A D','q_upper'),
 ('q_floor','QFloor','B0 L0 L A D','q_floor'),
 ('H_lower','HLower','A D','H_lower'),
 ('retained_cap','RetainedCap','B0 L0 c0 B L A D','retained_cap'),
 ('retained_width','RetainedWidth','B0 L0 B L A D','retained_width'),
 ('low_per_width','LowPerWidth','L0 A D','low_per_excess_width'),
 ('high_at_q','HighAtQ','B0 L0 B L A D','high_at_q'),
 ('high_deriv','HighDeriv','B0 L0 B L A D','high_density_derivative'),
 ('principal','Principal','B0 L0 B L A D','principal_reference'),
 ('second_ref','SecondRef','B0 L0 B L A D','second_reference'),
 ('second_diag','SecondDiag','B0 L0 B L A D','second_diagonal'),
 ('ref_upper','RefUpper','B0 L0 B L A D','reference_upper_positive'),
 ('selection_derivative','SelDeriv','A D','selection_monotonicity')]

def gen(record,idx,role):
    p={k:Q(x) for k,x in record['parameters'].items()}
    a=lambda keys:' '.join(rat(p[k]) for k in keys.split())
    ns=f'{role}{idx:03d}'
    cross=f"cross {a('B0 L0 B L')}"
    E=f"densE {a('B0 L0 L A D')} v"
    K=f"densK {a('L0 A')}"
    lines=[f'''/- Copyright (c) 2026. Builds on Sil's generic arithmetic (Apache-2.0),
Jacob Sussman's PR86 certificate layout, and OpenAI Codex-assisted rational instances.
Density source transition {idx}, with q >= 1/2. Generated by generate_lean.py.
Analytic interpretation is conditional on the preprint's 7/8 theorem. -/
import Submissions.density_batch.Source.HybridGates

set_option autoImplicit false
set_option maxHeartbeats 2000000
namespace QRH.DensityBatch
noncomputable section
namespace {ns}
open QRH.DensityBatch
open Hybrid

theorem cross_eq : {cross} = {rat(record['crossing'])} := by norm_num [cross]
theorem x_pos (v : ℝ) (h0 : 0 ≤ v) : 0 < 1 + {rat(p['D'])} * v := by nlinarith
theorem E_pos (v : ℝ) (h0 : 0 ≤ v) : 0 < {E} := by
  unfold densE; nlinarith
theorem F_pos (v : ℝ) (h0 : 0 ≤ v) : 0 < 15 * {E} - 6 * {K} := by
  unfold densE densK; nlinarith
''']
    for key,stem,keys,_ in SPEC:
        rec=record['gates'][key]
        n=sp.sympify(rec['numerator'],locals={'v':v});d=sp.sympify(rec['denominator'],locals={'v':v})
        fn=f'g{stem} {a(keys)}'
        lines += [f'def n{stem} (v : ℝ) : ℝ := {poly(n)}\n', f'def d{stem} (v : ℝ) : ℝ := {poly(d)}\n',f'''theorem cleared{stem} (v : ℝ) (h0 : 0 ≤ v) :
    {fn} v * d{stem} v = n{stem} v := by''']
        if stem.startswith('Q'):
            lines += ["  have hE := (E_pos v h0).ne'",f'  refine mul_eq_of_cleared hE (g{stem}_mul {a(keys)} v hE) ?_']
        else:
            lines += [f"  have hx : 1 + {rat(p['D'])} * v ≠ 0 := (x_pos v h0).ne'"]
            if stem=='HighAtQ':
                lines += ["  have hE := (E_pos v h0).ne'","  have hF := (F_pos v h0).ne'",f'  refine mul_eq_of_cleared (mul_ne_zero (mul_ne_zero hx hE) hF) (g{stem}_mul {a(keys)} v hx hE hF) ?_']
            else:
                h='(pow_ne_zero 2 hx)' if stem=='SelDeriv' else 'hx'
                lines += [f'  refine mul_eq_of_cleared {h} (g{stem}_mul {a(keys)} v hx) ?_']
        lines += [f'  simp only [n{stem}, d{stem}, densE, densK, width, cross_eq]', '  ring\n']
        boxes=sorted(rec['boxes'],key=lambda b:Q(b['lo']))
        for j,b in enumerate(boxes):
            lo,hi=Q(b['lo']),Q(b['hi']);nb,db=bernstein(n,lo,hi),bernstein(d,lo,hi)
            nd,dd=len(nb)-1,len(db)-1
            assert nd<=4 and dd<=4
            m,md,M=min(nb),min(db),max(db)
            for typ,bs in [('n',nb),('d',db)]:
                deg=len(bs)-1
                lines += [f'''theorem {typ}{stem}_bern{j} (t : ℝ) : {typ}{stem} ({rat(lo)} + ({rat(hi)} - {rat(lo)}) * t) =
    bern{deg} {' '.join(map(rat,bs))} t := by
  unfold {typ}{stem} bern{deg}; ring''']
            def bounds(deg,side):return f'bern{deg}_{side} '+('ht ht\' ' if deg else '')+' '.join(['(by norm_num)']*(deg+1))
            lines += [f'''theorem box{stem}_{j} (v : ℝ) (h0 : {rat(lo)} ≤ v) (h1 : v ≤ {rat(hi)}) :
    {rat(m/M)} ≤ {fn} v := by
  have hb := box_lower (g := {fn}) (n := n{stem}) (d := d{stem})
    (lo := {rat(lo)}) (hi := {rat(hi)}) (m := {rat(m)}) (M := {rat(M)}) (by norm_num) (by norm_num)
    (fun v h0 _ => cleared{stem} v (by linarith))
    (fun t ht ht' => by
      rw [n{stem}_bern{j}]
      exact {bounds(nd,'ge')})
    (fun t ht ht' => by
      rw [d{stem}_bern{j}]
      exact lt_of_lt_of_le (by norm_num : (0 : ℝ) < {rat(md)})
        ({bounds(dd,'ge')}))
    (fun t ht ht' => by
      rw [d{stem}_bern{j}]
      exact {bounds(dd,'le')})
    v h0 h1
  exact le_trans (le_of_eq (by norm_num)) hb
''']
        r=rat(rec['uniform_lower'])
        lines += [f'''theorem unif{stem} : UnifPos ({fn}) 0 ({rat(p['c'])} - {cross}) := by
  refine ⟨{r}, by norm_num, ?_⟩
  intro v h0 h1
  rw [cross_eq] at h1''']
        for j,b in enumerate(boxes):
            if j<len(boxes)-1:
                lines += [f"  by_cases h{j+2} : v ≤ {rat(b['hi'])}",f'  · exact le_trans (by norm_num) (box{stem}_{j} v (by linarith) h{j+2})']
            else:lines += [f'  exact le_trans (by norm_num) (box{stem}_{j} v (by linarith) (by linarith))\n']
    lines += [f'''end {ns}

open QRH.DensityBatch QRH.DensityBatch.Hybrid in
theorem hybridGates_{ns} : HybridGates {a('B0 L0 c0 B L c A D')} where
  width_pos := by rw [{ns}.cross_eq]; norm_num
  sel_den_pos := fun v h0 _ => {ns}.x_pos v h0
  dens_den_pos := fun v h0 _ => {ns}.E_pos v h0
  low_identity := fun v h0 _ =>
    lowDefect_eq _ _ _ _ _ v ({ns}.x_pos v h0).ne' ({ns}.E_pos v h0).ne'
  low_div_eq := fun v h0 _ =>
    lowDefect_div_eq _ _ _ _ _ v h0.ne' ({ns}.x_pos v h0.le).ne' ({ns}.E_pos v h0.le).ne'
  sel_hasDerivAt := fun v h0 _ => sel_hasDerivAt _ _ v ({ns}.x_pos v h0).ne'
''']
    lines += [f'  {field} := {ns}.unif{stem}' for _,stem,_,field in SPEC]
    lines += ['\nend\nend QRH.DensityBatch\n']
    return '\n'.join(lines)


if __name__ == "__main__":
    if len(sys.argv)!=3:raise SystemExit("Usage: python source/generate_lean.py round4 output/Source")
    INPUT=Path(sys.argv[1]);OUT=Path(sys.argv[2]);OUT.mkdir(parents=True,exist_ok=True)
    for role, title, theorem, chainfile in [('count', 'Count', 'final_source', 'Chain'), ('physical', 'Physical', 'physical_source', 'Physical')]:
        p = INPUT / f'{role}.json'
        receipt = json.loads(p.with_suffix('.receipt.json').read_text())
        assert receipt['source_sha256'] == hashlib.sha256(p.read_bytes()).hexdigest()
        assert receipt['low_reserve'] == '1/10000'
        rows = receipt['cases']
        for i, row in enumerate(rows, 1):
            (OUT / f'{title}{i:03d}.lean').write_text(gen(row, i, title))
        src = lambda p, keys: 'QRH.Record1252270103Source.GlobalSource ' + ' '.join((rat(p[k]) for k in keys.split()))
        out = ["/- Exact source chain with LOW reserve 1/10000.\nBuilds on OpenAI, Hailey Collet, Sil, ArviFoxy, Jacob Sussman and Rohan Arun.\nApache-2.0; substantially AI-assisted by OpenAI Codex.\nAnalytic conclusions remain conditional on the preprint's 7/8 theorem. -/\nimport Submissions.density_batch.Source.Step\nimport Submissions.density_split_fine_chain.Source.ChainK15"]
        out += [f'import Submissions.density_batch.Source.{title}{i:03d}' for i in range(1, len(rows) + 1)]
        out += ['set_option autoImplicit false\nset_option maxHeartbeats 2000000\nnamespace QRH.DensityBatch\nnoncomputable section\nopen QRH.SilDensitySplit QRH.SilDensitySplit.K15', f"\ntheorem {theorem} (hβ : (51/100:ℝ) ≤ OAI.SevenEighths.HeckeZeroSupremum.beta) :\n    {src(rows[-1]['parameters'], 'B L c')} := by\n  have s000 : {src(rows[0]['parameters'], 'B0 L0 c0')} := " + ('QRH.SilDensitySplit.K15.final_source hβ' if role == 'count' else 'by\n    simpa only [Face.Source, bootFace] using boot_source hβ')]
        for i, row in enumerate(rows, 1):
            out += [f"  have s{i:03d} : {src(row['parameters'], 'B L c')} :=\n    QRH.DensityBatch.density_step hybridGates_{title}{i:03d}\n      ⟨by norm_num, by norm_num, by norm_num, by norm_num, by norm_num, by norm_num⟩\n      (by norm_num) (by norm_num) (by norm_num) hβ s{i - 1:03d}"]
        out += [f'  exact s{len(rows):03d}\nend\nend QRH.DensityBatch\n']
        (OUT / f'{chainfile}.lean').write_text('\n'.join(out))
        print('Generated', role, len(rows), 'instances and chain', flush=True)
