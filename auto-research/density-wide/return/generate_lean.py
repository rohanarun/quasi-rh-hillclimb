NS='QRH.DensityWide.Return'
BASE_SIMP=('V,D,A,C0,Z,U,oldD,oldC,countJ,countN,countT,RN,MN,DJ,branchB,branchL,'
 'branchCap,branchZ,isCap,c,h,theta,ell,x,y,kappa,dm,dp,d0,physicalB,physicalLambda,'
 'physicalCap,countCB,countCL,countCap,naturalK,sMinus,mMinus,reserve,numeratorCap,'
 'Record12518109.Bernstein.bsum,Record12518109.Bernstein.bterm')
ADMISSION_SIMP='admissionGuard,lowerM,upperM,naturalM,derivativeD,derivativeA,derivativeC,derivativeU,derivativeJ,'+BASE_SIMP
ROW_SIMP='rowMargin,Ebase,'+BASE_SIMP
BRANCHES={'old':C.branch(),'capP':C.branch(C.PHYS,True),'C':C.branch(C.COUNT)}
EDGES=['oldSmall','oldSwitch','newSwitch','newTop']

def q(v):return '('+str(F(v))+':ℝ)'
def header(title,imports=None,namespace=NS):
 return f'''/- Copyright (c) 2026 Sil, Hailey Collet, and contributors. Apache-2.0.
AI-assisted widened-density extension, conditional on the preprint 7/8 theorem.
{title}
Generated by generate_lean.py from exact rational inputs. Bernstein checker and
return layout descend from Collet, Repeated marks, Sil, and #86 fine-chain. -/
{imports or 'import '+PREFIX+'.Formulas'}
set_option autoImplicit false
set_option linter.unnecessarySeqFocus false
set_option maxHeartbeats 400000
namespace {namespace}
noncomputable section
'''
def footer(namespace=NS):return f'end\nend {namespace}\n'
def hypotheses(box):
 a,b,c,d=box
 return f'{{δ p : ℝ}} (hδ : δ ∈ Set.Icc {q(a)} {q(b)})\n (hp : p ∈ Set.Icc {q(c)} {q(d)})'

def polynomial_certificate(name,target,pol,box,simp):
 mat=C.bern(pol,box);n=len(mat)-1;m=len(mat[0])-1
 minimum=min(v for row in mat for v in row)
 assert minimum>0,(name,minimum)
 a,b,c,d=map(F,box)
 coeff=[[(v-minimum)*comb(n,i)*comb(m,j)/(b-a)**n/(d-c)**m for j,v in enumerate(row)] for i,row in enumerate(mat)]
 arr='!['+',\n'.join('!['+', '.join(q(v) for v in row)+']' for row in coeff)+']'
 return f'''def {name}_coefficients : Fin {n+1} → Fin {m+1} → ℝ := {arr}
theorem {name}_identity (δ p : ℝ) : {target} =
 Record12518109.Bernstein.bsum {n} {m} {q(minimum)} {name}_coefficients {q(a)} {q(b)} {q(c)} {q(d)} δ p := by
 norm_num [{simp},{name}_coefficients,Fin.sum_univ_succ] <;> ring
theorem {name}_pos {hypotheses(box)} : 0 < {target} := by
 rw [{name}_identity]
 apply Record12518109.Bernstein.bsum_pos (by norm_num) _ hδ hp
 intro i j
 fin_cases i <;> fin_cases j <;> norm_num [{name}_coefficients]
'''

def recursive_certificate(name,target,pol,box,simp,depth=0):
 if C.bound(pol,box)>0:
  STATS['margin_identities']+=1
  return polynomial_certificate(name,target,pol,box,simp)
 assert depth<20,(name,box)
 a,b,c,d=box
 if b-a>=d-c:
  cut=(a+b)/2;lb=(a,cut,c,d);rb=(cut,b,c,d);axis='δ'
  largs='⟨hδ.1,hs⟩ hp';rargs='⟨hs,hδ.2⟩ hp'
 else:
  cut=(c+d)/2;lb=(a,b,c,cut);rb=(a,b,cut,d);axis='p'
  largs='hδ ⟨hp.1,hs⟩';rargs='hδ ⟨hs,hp.2⟩'
 left=recursive_certificate(name+'_l',target,pol,lb,simp,depth+1)
 right=recursive_certificate(name+'_r',target,pol,rb,simp,depth+1)
 return left+right+f'''theorem {name}_pos {hypotheses(box)} : 0 < {target} := by
 rcases le_total {axis} {q(cut)} with hs | hs
 · exact {name}_l_pos {largs}
 · exact {name}_r_pos {rargs}
'''

def admissions():
 for i,(kind,a,b,c) in enumerate(C.WINDOWS,1):
  branch='capP' if kind=='cap' else 'C';box=(F(a),F(b),F(c),F(1,2));stem=f'admission{i:02d}'
  out=[header(f'Admission window {i:02d}: 15 exact guards.')]
  for j,g in enumerate(BRANCHES[branch][2]):
   out.append(polynomial_certificate(f'{stem}_{j:02d}',f'admissionGuard .{branch} δ p {j}',C.poly(g),box,ADMISSION_SIMP))
  out.append(f'theorem {stem}_all {hypotheses(box)} (j : Fin 15) : 0<admissionGuard .{branch} δ p j := by\n fin_cases j\n')
  out.extend(f' · exact {stem}_{j:02d}_pos hδ hp\n' for j in range(15));out.append(footer())
  (OUT/'Rows'/f'Admission{i:02d}.lean').write_text(''.join(out))

def margins():
 ell=4*(1-C.THETA)-s.Rational(1,3);y=C.H-2*ell;k=2*C.THETA-1
 ds=[s.Rational(1,200),s.Rational(19,25),s.Rational(19,25),C.H+s.Rational(1,10**10)]
 cs=[min(d,2*y-d)/(6*k) if i<2 else min(s.Rational(3,50)*d,(2*y-(2-C.PHYS[0])*d)/C.PHYS[1]) for i,d in enumerate(ds)]
 ret={}
 for branch,(J,N,_) in BRANCHES.items():
  for edge,d,cap in zip(EDGES,ds,cs):
   E=s.Rational(1,2)+s.Rational(13,75)*C.H-y/2-ell/2-s.Rational(9,100)*d+C.delta/2+C.delta*C.p*(ell-cap/2)
   ret[edge,branch]=C.poly(s.expand(J*(C.THETA-C.RESERVE-E)-s.Rational(3,4)*d*N))
 return ret

def edge_rows(layout):
 polys=margins()
 for filename,rows in layout.items():
  out=[header('Exact edge margin certificates; inherited compact cover.')]
  for r in rows:
   box=tuple(map(F,r['box']));edge=r['edge'];branch=r['branch']
   out.append(recursive_certificate(r['name'],f'rowMargin .{edge} .{branch} δ p',polys[edge,branch],box,ROW_SIMP+f',edgeD_{edge},edgeC_{edge}'))
  out.append(footer());(OUT/'Rows'/filename).write_text(''.join(out))

def region(rows):
 return (min(r['box'][0] for r in rows),max(r['box'][1] for r in rows),min(r['box'][2] for r in rows),max(r['box'][3] for r in rows))
def partition(rows):
 if len(rows)==1:return ('leaf',rows[0],region(rows))
 a,b,c,d=region(rows);opts=[]
 for axis,low,hi in [('δ',0,1),('p',2,3)]:
  for cut in sorted({r['box'][hi] for r in rows}):
   if any(r['box'][low]<cut<r['box'][hi] for r in rows):continue
   left=[r for r in rows if r['box'][hi]<=cut];right=[r for r in rows if r['box'][low]>=cut]
   if not left or not right or len(left)+len(right)!=len(rows):continue
   lr=region(left);rr=region(right)
   valid=(lr==(a,cut,c,d) and rr==(cut,b,c,d)) if axis=='δ' else (lr==(a,b,c,cut) and rr==(a,b,cut,d))
   if valid:opts.append((abs(len(left)-len(right)),axis,cut,left,right))
 assert opts,('untiled',rows)
 _,axis,cut,left,right=min(opts,key=lambda z:z[0])
 return ('split',axis,cut,partition(left),partition(right),region(rows))
def envelope_target(edge):return f'Ebase (edgeD .{edge}) (edgeC .{edge}) δ p+3/4*edgeD .{edge}*(@GenericCount.envelope finalCountScheme kappa δ p)<theta-reserve'
def cover_leaf(row):
 name='envelope_'+row['name'];box=row['box'];edge=row['edge'];branch=row['branch'];a,b,c,d=box
 out=f'''theorem {name} {hypotheses(box)} : {envelope_target(edge)} := by
 have hd0 : δ∈Set.Icc 0 (3/4) := by constructor <;> linarith [hδ.1,hδ.2]
 have hp0 : p∈Set.Icc 0 (1/2) := by constructor <;> linarith [hp.1,hp.2]
'''
 if branch=='old':out+=' have hR := finiteEnvelope_le_old hd0 hp0\n'
 else:
  available=[]
  for i,(kind,wa,wb,wc) in enumerate(C.WINDOWS,1):
   if branch==('capP' if kind=='cap' else 'C') and wa<=a and b<=wb and wc<=c and d<=F(1,2):available.append((i,(wa,wb,wc,F(1,2))))
  assert available,(row,'no compatible window')
  wi,(wa,wb,wc,wd)=available[0]
  out+=f''' have ha : returnWindow{wi:02d}.Available δ p := by
  change δ∈Set.Icc {q(wa)} {q(wb)} ∧ p∈Set.Icc {q(wc)} {q(wd)}
  constructor <;> constructor <;> linarith [hδ.1,hδ.2,hp.1,hp.2]
 have hR : @GenericCount.envelope finalCountScheme kappa δ p≤countN .{branch} δ p/countJ .{branch} δ p := finiteEnvelope_le_window returnWindow{wi:02d} window{wi:02d}_mem ha
'''
 out+=f" exact exponent_lt_of_margin (countJ_pos .{branch} hd0 hp0) ({row['name']}_pos hδ hp) hR\n"
 return name,out

def emit_cover_node(tree,edge,out,counter):
 if tree[0]=='leaf':
  name,code=cover_leaf(tree[1]);out.append(code);return name
 _,axis,cut,left,right,box=tree
 ln=emit_cover_node(left,edge,out,counter);rn=emit_cover_node(right,edge,out,counter)
 name=f'cover_{edge}_{counter[0]:03d}';counter[0]+=1
 code=f'theorem {name} {hypotheses(box)} : {envelope_target(edge)} := by\n rcases le_total {axis} {q(cut)} with hs | hs\n'
 if axis=='δ':code+=f' · exact {ln} ⟨hδ.1,hs⟩ hp\n · exact {rn} ⟨hs,hδ.2⟩ hp\n'
 else:code+=f' · exact {ln} hδ ⟨hp.1,hs⟩\n · exact {rn} hδ ⟨hs,hp.2⟩\n'
 out.append(code);return name

def edge_cover(layout):
 imports='import '+PREFIX+'.FinalEnvelopeBounds\n'+'\n'.join('import '+PREFIX+'.Rows.'+Path(f).stem for f in layout)
 out=[header('Exact closed cover of all four conductor edges.',imports,NS+'.FinalEdges'),'open QRH.Record1252270103Return\n']
 for i in range(1,17):out.append(f'theorem window{i:02d}_mem : returnWindow{i:02d}∈returnWindows := by simp [returnWindows]\n')
 rows=[{**r,'box':tuple(map(F,r['box']))} for rs in layout.values() for r in rs]
 for edge in EDGES:
  er=[r for r in rows if r['edge']==edge]
  assert region(er)==(F(0),F(3,4),F(0),F(1,2))
  root=emit_cover_node(partition(er),edge,out,[1])
  out.append(f'''theorem edge_{edge}_certificate {{δ p:ℝ}} (hδ:δ∈Set.Icc 0 (3/4))
 (hp:p∈Set.Icc 0 (1/2)) : {envelope_target(edge)} := by
 exact {root} (by simpa using hδ) (by simpa using hp)
''')
 out.append('''theorem closed_envelope_return_cover (e : Edge) {δ p : ℝ} (hδ : δ∈Set.Icc 0 (3/4))
 (hp : p∈Set.Icc 0 (1/2)) : Ebase (edgeD e) (edgeC e) δ p+3/4*edgeD e*(@GenericCount.envelope finalCountScheme kappa δ p)<theta-reserve := by
 cases e with
''')
 out.extend(f' | {edge} => exact edge_{edge}_certificate hδ hp\n' for edge in EDGES)
 out.append(footer(NS+'.FinalEdges'));(OUT/'EdgeCertificates.lean').write_text(''.join(out))

def extract_layout(upstream):
 result={}
 pattern=r'theorem (row[0-9]+[ab]?)_pos \{δ p : ℝ\} \(hδ : δ ∈ Set.Icc \(([^:]+):ℝ\) \(([^:]+):ℝ\)\)\s*\(hp : p ∈ Set.Icc \(([^:]+):ℝ\) \(([^:]+):ℝ\)\) : 0 < rowMargin \.(\w+) \.(\w+) δ p'
 for f in sorted((upstream/'Rows').glob('Edge_*.lean')):
  rows=[]
  for name,a,b,c,d,edge,branch in re.findall(pattern,f.read_text()):
   if name=='row011':b='11/32'
   if name=='row012':a='11/32'
   rows.append(dict(name=name,box=[a,b,c,d],edge=edge,branch=branch))
  assert rows,f
  result[f.name]=rows
 assert sum(map(len,result.values()))==32,result
 (ROOT/'compact-layout.json').write_text(json.dumps(result,indent=2)+'\n')
 return result

